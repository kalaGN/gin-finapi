CREATE TABLE IF NOT EXISTS api_customers (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '客户ID',
    name VARCHAR(128) NOT NULL COMMENT '客户名称',
    status TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '0禁用，1启用',
    remark VARCHAR(500) NOT NULL DEFAULT '' COMMENT '备注',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT chk_customer_status CHECK (status IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='API客户';

CREATE TABLE IF NOT EXISTS api_keys (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT 'API Key内部ID',
    customer_id BIGINT UNSIGNED NOT NULL COMMENT '所属客户',
    name VARCHAR(128) NOT NULL COMMENT '凭据用途名称',
    api_key_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'API Key的SHA256小写摘要',
    secret_ciphertext BLOB NOT NULL COMMENT 'AES256GCM密文，含nonce和tag',
    secret_key_id VARCHAR(64) NOT NULL COMMENT '加密密钥标识，密钥不存本表',
    status TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '0禁用，1启用',
    expires_at BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Unix秒，0永久',
    remark VARCHAR(500) NOT NULL DEFAULT '' COMMENT '备注',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_api_key_digest (api_key_digest),
    KEY idx_customer_id (customer_id),
    CONSTRAINT chk_api_key_status CHECK (status IN (0, 1)),
    CONSTRAINT fk_api_key_customer FOREIGN KEY (customer_id) REFERENCES api_customers (id) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='客户API凭据';

CREATE TABLE IF NOT EXISTS api_products (
    pcode INT UNSIGNED NOT NULL COMMENT '公开产品编码',
    name VARCHAR(128) NOT NULL COMMENT '产品名称',
    variable_map JSON NOT NULL COMMENT '变量名称与Mongo数据下标映射',
    remark VARCHAR(500) NOT NULL DEFAULT '' COMMENT '备注',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (pcode),
    CONSTRAINT chk_product_pcode CHECK (pcode BETWEEN 10001 AND 99999)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='API产品及变量映射';

CREATE TABLE IF NOT EXISTS api_key_products (
    api_key_id BIGINT UNSIGNED NOT NULL COMMENT 'API Key内部ID',
    pcode INT UNSIGNED NOT NULL COMMENT '产品编码',
    status TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '0禁用，1启用',
    expires_at BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Unix秒，0永久',
    remark VARCHAR(500) NOT NULL DEFAULT '' COMMENT '授权备注',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (api_key_id, pcode),
    KEY idx_product_pcode (pcode),
    CONSTRAINT chk_key_product_status CHECK (status IN (0, 1)),
    CONSTRAINT fk_key_product_key FOREIGN KEY (api_key_id) REFERENCES api_keys (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_key_product_product FOREIGN KEY (pcode) REFERENCES api_products (pcode) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='API Key产品授权';
